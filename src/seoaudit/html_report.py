"""Standalone HTML report. No external assets, so it opens from a file:// URL."""

import html
from collections import defaultdict
from urllib.parse import urlsplit

from seoaudit.catalog import Check, catalog_for
from seoaudit.models import SEVERITIES, AuditReport, Issue
from seoaudit.report import LIMITATIONS, summarize
from seoaudit.score import COUNT_CAP, WEIGHTS
from seoaudit.thresholds import Thresholds

_CATEGORY_LABELS = {
    "crawl": "Crawl",
    "links": "Links",
    "indexation": "Indexation",
    "metadata": "Metadata",
    "content": "Content",
}


def render_html(report: AuditReport) -> str:
    summary = summarize(report)
    thresholds = _thresholds(report)
    catalog = catalog_for(thresholds)
    host = urlsplit(report.start_url).netloc or report.start_url
    groups = _groups(report.issues)
    score = "—" if report.score.overall is None else f"{report.score.overall:.1f}"
    parts = [
        "<!DOCTYPE html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        '<meta name="robots" content="noindex">',
        f"<title>SEO audit · {html.escape(host)}</title>",
        f"<style>{_CSS}</style>",
        "</head>",
        "<body>",
        '<header class="top">',
        '<p class="brand">seoaudit <span>' + html.escape(report.version) + "</span></p>",
        f"<h1>{html.escape(host)}</h1>",
        f'<p class="start"><a href="{html.escape(report.start_url, quote=True)}">{html.escape(report.start_url)}</a></p>',
        '<p class="when">'
        + html.escape(report.started_at)
        + " · "
        + html.escape(_duration(report.duration_seconds))
        + " · "
        + str(summary["requests"])
        + " requests</p>",
        "</header>",
        "<main>",
        _score_section(report, summary, score),
        _filters(),
        "<section>",
        "<h2>Prioritized issues</h2>",
        _issue_groups(groups, catalog),
        "</section>",
        _pages_section(report),
        _method_section(thresholds),
        "</main>",
        "<footer>",
        "<p>Generated by seoaudit "
        + html.escape(report.version)
        + ". The score sorts this crawl. It is not a ranking prediction.</p>",
        "</footer>",
        f"<script>{_JS}</script>",
        "</body>",
        "</html>",
        "",
    ]
    return "\n".join(parts)


def _score_section(report: AuditReport, summary: dict[str, object], score: str) -> str:
    counts = summary["by_severity"]
    assert isinstance(counts, dict)
    cards = []
    for severity in SEVERITIES:
        cards.append(
            '<li data-severity="'
            + severity
            + '"><span>'
            + severity
            + "</span><strong>"
            + str(counts[severity])
            + "</strong></li>"
        )
    categories = []
    for key, label in _CATEGORY_LABELS.items():
        value = report.score.categories.get(key)
        shown = "—" if value is None else f"{value:.1f}"
        width = 0 if value is None else value
        categories.append(
            '<div class="cat"><div class="cat-label"><span>'
            + label
            + "</span><span>"
            + shown
            + '</span></div><div class="track"><div class="fill" style="width:'
            + str(width)
            + '%"></div></div></div>'
        )
    note = (
        "No HTML documents were fetched, so there is no score."
        if report.score.overall is None
        else "Triage score for this crawl. Category bars use the same weights on that group of checks."
    )
    considered = summary["external_considered"]
    checked = summary["external_checked"]
    external = f"{checked} checked"
    if isinstance(considered, int) and isinstance(checked, int) and considered > checked:
        external += f", {considered - checked} not checked"
    stats = [
        ("Pages fetched", summary["pages"]),
        ("Indexable documents", summary["indexable"]),
        ("Sitemap URLs", summary["sitemap_urls"]),
        ("Blocked by robots", summary["blocked"]),
        ("External links", external),
        ("Robots.txt", _robots_label(report)),
    ]
    stat_html = "".join(
        "<div><dt>" + html.escape(label) + "</dt><dd>" + html.escape(str(value)) + "</dd></div>"
        for label, value in stats
    )
    return (
        '<section class="overview">'
        '<div class="score-card"><p class="eyebrow">Health score</p>'
        f'<p class="score">{score}</p><p class="note">{html.escape(note)}</p></div>'
        '<ul class="severities">'
        + "".join(cards)
        + '</ul><div class="categories">'
        + "".join(categories)
        + '</div><dl class="stats">'
        + stat_html
        + "</dl></section>"
    )


def _filters() -> str:
    buttons = ['<button type="button" data-filter="all" class="on">All</button>']
    for severity in SEVERITIES:
        buttons.append(f'<button type="button" data-filter="{severity}">{severity}</button>')
    return (
        '<div class="filters" role="toolbar" aria-label="Filter issues">'
        + "".join(buttons)
        + "</div>"
    )


def _issue_groups(groups: list[tuple[str, str, list[Issue]]], catalog: dict[str, Check]) -> str:
    if not groups:
        return '<p class="empty">No issues. Every check that ran came back clean.</p>'
    blocks = []
    for severity, code, issues in groups:
        check = catalog.get(code)
        summary = check.summary if check is not None and hasattr(check, "summary") else ""
        rows = []
        for issue in issues:
            rows.append(
                '<li><a href="'
                + html.escape(issue.url, quote=True)
                + '">'
                + html.escape(issue.url)
                + "</a><span>"
                + html.escape(issue.message)
                + "</span></li>"
            )
        hidden = ""
        visible = rows
        if len(rows) > 8:
            visible = rows[:8]
            hidden = (
                "<details><summary>"
                + str(len(rows) - 8)
                + " more</summary><ul>"
                + "".join(rows[8:])
                + "</ul></details>"
            )
        noun = "page" if len(issues) == 1 else "pages"
        blocks.append(
            '<article class="group" data-severity="'
            + severity
            + '"><header><span class="pill">'
            + severity
            + "</span><h3><code>"
            + html.escape(code)
            + '</code></h3><span class="count">'
            + str(len(issues))
            + " "
            + noun
            + "</span></header><p>"
            + html.escape(str(summary))
            + "</p><ul>"
            + "".join(visible)
            + "</ul>"
            + hidden
            + "</article>"
        )
    return "".join(blocks)


def _pages_section(report: AuditReport) -> str:
    rows = []
    for page in report.pages:
        depth = "—" if page.depth is None else str(page.depth)
        status = "—" if page.status is None else str(page.status)
        title = page.title or page.error or ""
        rows.append(
            '<tr><td><a href="'
            + html.escape(page.url, quote=True)
            + '">'
            + html.escape(page.url)
            + "</a></td><td>"
            + status
            + "</td><td>"
            + depth
            + "</td><td>"
            + str(page.word_count)
            + "</td><td>"
            + _bytes(page.html_bytes)
            + "</td><td>"
            + ("yes" if page.indexable() else "no")
            + "</td><td>"
            + html.escape(title)
            + "</td></tr>"
        )
    body = "".join(rows) or '<tr><td colspan="7">No pages fetched.</td></tr>'
    return (
        '<section><h2>Pages</h2><div class="table-wrap"><table>'
        "<thead><tr><th>URL</th><th>Status</th><th>Depth</th><th>Words</th>"
        "<th>HTML</th><th>Indexable</th><th>Title</th></tr></thead><tbody>"
        + body
        + "</tbody></table></div></section>"
    )


def _method_section(thresholds: Thresholds) -> str:
    weights = ", ".join(
        f"{name} {int(WEIGHTS[name]) if WEIGHTS[name].is_integer() else WEIGHTS[name]}"
        for name in SEVERITIES
    )
    formula = (
        f"points = weight x (min(count, {COUNT_CAP}) + 1) / 2. "
        f"Weights: {weights}. Info scores 0. "
        "The fifth finding of a code is the last one that adds points, so one template fault "
        "cannot deduct more than three times its weight. The overall score is 100 minus the sum, floored at 0."
    )
    limits = (
        f"Title {thresholds.title_min}-{thresholds.title_max} characters. "
        f"Meta description {thresholds.meta_min}-{thresholds.meta_max} characters. "
        f"Thin content is under {thresholds.thin_words} visible words; under {thresholds.very_thin_words} is very thin. "
        f"HTML over {thresholds.html_large_bytes // 1000} KB is large, and over {thresholds.html_very_large_bytes // 1000} KB is very large. "
        f"Click depth {thresholds.deep_depth} or more is deep. The start document is depth 0."
    )
    items = "".join("<li>" + html.escape(item) + "</li>" for item in LIMITATIONS)
    return (
        '<section class="method"><h2>How the score is calculated</h2><p>'
        + html.escape(formula)
        + "</p><p>"
        + html.escape(limits)
        + "</p><h2>Limits of this crawl</h2><ul>"
        + items
        + "</ul></section>"
    )


def _groups(issues: list[Issue]) -> list[tuple[str, str, list[Issue]]]:
    buckets: dict[tuple[str, str], list[Issue]] = defaultdict(list)
    rank: dict[str, int] = {name: index for index, name in enumerate(SEVERITIES)}
    for issue in issues:
        buckets[(issue.severity, issue.code)].append(issue)
    ordered = sorted(
        buckets.items(), key=lambda item: (rank[item[0][0]], -len(item[1]), item[0][1])
    )
    return [(severity, code, grouped) for (severity, code), grouped in ordered]


def _thresholds(report: AuditReport) -> Thresholds:
    raw = report.settings.get("thresholds")
    if not isinstance(raw, dict):
        return Thresholds()
    known = {field for field in Thresholds.__dataclass_fields__}
    values = {key: value for key, value in raw.items() if key in known}
    try:
        return Thresholds(**values)
    except TypeError:
        return Thresholds()


def _robots_label(report: AuditReport) -> str:
    if report.robots_unavailable:
        return f"unavailable ({report.robots_status})"
    if report.robots_found:
        delay = ""
        if report.crawl_delay:
            delay = f", crawl-delay {report.crawl_delay:g}s"
        return f"found{delay}"
    return "not found"


def _duration(seconds: float) -> str:
    if seconds < 60:
        return f"{seconds:.1f}s"
    minutes, rest = divmod(int(seconds), 60)
    return f"{minutes}m {rest}s"


def _bytes(size: int) -> str:
    if size < 1024:
        return f"{size} B"
    if size < 1024 * 1024:
        return f"{size / 1024:.1f} KB"
    return f"{size / (1024 * 1024):.2f} MB"


